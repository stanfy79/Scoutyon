import React, { useState } from 'react';
import type { Quote } from '../../types/quote.types';
import { StatusBadge } from '../common/StatusBadge';
import { formatCurrency } from '../../utils/formatCurrency';
import { formatDate } from '../../utils/formatDate';
import { Search, Eye, X, FileText, CreditCard } from 'lucide-react';

interface QuoteTableProps {
  quotes: Quote[];
  onViewDetails: (quote: Quote) => void;
  onPreparePayment: (quoteId: string) => void;
  onReject: (quoteId: string) => void;
}

export const QuoteTable: React.FC<QuoteTableProps> = ({
  quotes,
  onViewDetails,
  onPreparePayment,
  onReject,
}) => {
  const [filter, setFilter] = useState<string>('all');
  const [search, setSearch] = useState<string>('');

  const filterTabs = [
    { id: 'all', label: 'All Quotes' },
    { id: 'pending', label: 'Pending' },
    { id: 'approved', label: 'Approved' },
    { id: 'paid', label: 'Paid / Settled' },
    { id: 'rejected', label: 'Rejected' },
  ];

  const filteredQuotes = quotes.filter((q) => {
    if (filter !== 'all' && q.status !== filter) return false;
    if (search.trim()) {
      const query = search.toLowerCase();
      return (
        q.provider.toLowerCase().includes(query) ||
        q.description.toLowerCase().includes(query)
      );
    }
    return true;
  });

  return (
    <div className="space-y-4">
      {/* Controls: Search and Filter Tabs */}
      <div className="flex flex-col sm:flex-row items-stretch sm:items-center justify-between gap-3">
        {/* Filter Pills */}
        <div className="flex items-center gap-1.5 overflow-x-auto pb-1 sm:pb-0">
          {filterTabs.map((tab) => (
            <button
              key={tab.id}
              onClick={() => setFilter(tab.id)}
              className={`px-3 py-1.5 rounded-lg text-xs font-medium whitespace-nowrap transition-colors ${
                filter === tab.id
                  ? 'bg-indigo-600/20 text-indigo-300 border border-indigo-500/30'
                  : 'text-gray-400 hover:text-gray-200 hover:bg-white/5 border border-transparent'
              }`}
            >
              {tab.label}
            </button>
          ))}
        </div>

        {/* Search */}
        <div className="relative min-w-[220px]">
          <Search className="w-3.5 h-3.5 text-gray-500 absolute left-3 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search provider or service..."
            className="w-full bg-[#121620] border border-[#202738] rounded-lg pl-8 pr-3 py-1.5 text-xs text-gray-200 placeholder-gray-500 focus:outline-none focus:border-indigo-500"
          />
        </div>
      </div>

      {filteredQuotes.length === 0 ? (
        <div className="bg-[#121620] border border-[#202738] rounded-xl p-8 text-center">
          <FileText className="w-6 h-6 text-gray-500 mx-auto mb-2" />
          <p className="text-sm font-semibold text-gray-300">No quotes found</p>
          <p className="text-xs text-gray-500 mt-0.5">
            {search
              ? 'Try adjusting your search criteria.'
              : 'Quotes generated by the research agent will appear here.'}
          </p>
        </div>
      ) : (
        <>
          {/* Desktop Table View */}
          <div className="hidden md:block bg-[#121620] border border-[#202738] rounded-xl overflow-hidden shadow-sm">
            <table className="w-full text-left text-xs">
              <thead className="bg-[#161B26] border-b border-[#202738] text-gray-400 uppercase tracking-wider font-semibold text-[10px]">
                <tr>
                  <th className="px-4 py-3">Vendor / Service</th>
                  <th className="px-4 py-3">Price</th>
                  <th className="px-4 py-3">Status</th>
                  <th className="px-4 py-3">Date</th>
                  <th className="px-4 py-3 text-right">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-[#1B2230]">
                {filteredQuotes.map((q) => (
                  <tr key={q._id} className="hover:bg-[#151A25] transition-colors">
                    <td className="px-4 py-3.5 max-w-xs">
                      <div className="font-semibold text-gray-200">{q.provider}</div>
                      <div className="text-[11px] text-gray-400 truncate mt-0.5">
                        {q.description}
                      </div>
                    </td>
                    <td className="px-4 py-3.5 whitespace-nowrap">
                      <span className="font-bold text-gray-100">
                        {formatCurrency(q.price, q.currency)}
                      </span>
                    </td>
                    <td className="px-4 py-3.5 whitespace-nowrap">
                      <StatusBadge status={q.status} />
                    </td>
                    <td className="px-4 py-3.5 whitespace-nowrap text-gray-400 text-[11px]">
                      {formatDate(q.createdAt)}
                    </td>
                    <td className="px-4 py-3.5 whitespace-nowrap text-right">
                      <div className="flex items-center justify-end gap-1.5">
                        <button
                          onClick={() => onViewDetails(q)}
                          className="p-1.5 text-gray-400 hover:text-gray-200 hover:bg-white/5 rounded-md transition-colors"
                          title="View Specifications"
                        >
                          <Eye className="w-3.5 h-3.5" />
                        </button>
                        {q.status === 'pending' && (
                          <>
                            <button
                              onClick={() => onReject(q._id)}
                              className="p-1.5 text-red-400 hover:text-red-300 hover:bg-red-950/40 rounded-md transition-colors"
                              title="Reject Quote"
                            >
                              <X className="w-3.5 h-3.5" />
                            </button>
                          </>
                        )}
                        {(q.status === 'pending' || q.status === 'approved') && (
                          <button
                            onClick={() => onPreparePayment(q._id)}
                            className="p-1.5 text-indigo-300 hover:text-indigo-200 hover:bg-indigo-950/40 rounded-md transition-colors"
                            title="Prepare payment for review"
                          >
                            <CreditCard className="w-3.5 h-3.5" />
                          </button>
                        )}
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          {/* Mobile Card List View */}
          <div className="grid grid-cols-1 gap-3 md:hidden">
            {filteredQuotes.map((q) => (
              <div
                key={q._id}
                className="bg-[#121620] border border-[#202738] rounded-xl p-4 space-y-3"
              >
                <div className="flex items-start justify-between gap-2">
                  <div>
                    <h4 className="text-sm font-bold text-gray-200">{q.provider}</h4>
                    <p className="text-xs text-gray-400 mt-0.5 line-clamp-2">
                      {q.description}
                    </p>
                  </div>
                  <StatusBadge status={q.status} />
                </div>

                <div className="flex items-center justify-between text-xs pt-2 border-t border-[#1C2330]">
                  <span className="font-bold text-gray-100 text-sm">
                    {formatCurrency(q.price, q.currency)}
                  </span>
                  <span className="text-[11px] text-gray-500">
                    {formatDate(q.createdAt)}
                  </span>
                </div>

                <div className="flex items-center justify-end gap-2 pt-2 border-t border-[#1C2330]">
                  <button
                    onClick={() => onViewDetails(q)}
                    className="px-2.5 py-1 text-xs text-gray-300 bg-white/5 hover:bg-white/10 rounded-md"
                  >
                    Details
                  </button>
                  {q.status === 'pending' && (
                    <>
                      <button
                        onClick={() => onReject(q._id)}
                        className="px-2.5 py-1 text-xs text-red-400 bg-red-950/30 hover:bg-red-950/50 rounded-md border border-red-900/40"
                      >
                        Reject
                      </button>
                    </>
                  )}
                  {(q.status === 'pending' || q.status === 'approved') && (
                    <button
                      onClick={() => onPreparePayment(q._id)}
                      className="px-2.5 py-1 text-xs text-indigo-200 bg-indigo-950/40 hover:bg-indigo-900/50 rounded-md border border-indigo-800/40 font-medium"
                    >
                      Prepare payment
                    </button>
                  )}
                </div>
              </div>
            ))}
          </div>
        </>
      )}
    </div>
  );
};
